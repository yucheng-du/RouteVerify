#!/usr/bin/env python3
"""Build the three manuscript tables for Appendix app:verification-metrics.

Generator: docs/results/verification_metrics_cpu_20260917/make_paper_tables.py
Inputs (read-only, full precision):
  baseline/baseline_panels_v1.csv
  flips/flip_panels_v1.csv
  normalized_t/normalized_t_panels_v1.csv
Outputs (body-only LaTeX, caller owns float/caption/label):
  <overleaf>/tables/verification_baseline_20260917.tex
  <overleaf>/tables/decision_flips_20260917.tex
  <overleaf>/tables/normalized_effects_20260917.tex
  paper_tables_provenance_20260917.json

Deterministic: no randomness, no network, no model forwards. Every emitted
number is re-parsed from the written .tex and asserted equal to the CSV value
formatted to 4 decimals.
"""

import datetime
import hashlib
import json
import os
import re
import sys

import pandas as pd

OUT = os.path.dirname(os.path.abspath(__file__))
TEX_DIR = os.path.join(OUT, "tables")
os.makedirs(TEX_DIR, exist_ok=True)

BASELINE_CSV = os.path.join(OUT, "baseline", "baseline_panels_v1.csv")
FLIPS_CSV = os.path.join(OUT, "flips", "flip_panels_v1.csv")
NORM_CSV = os.path.join(OUT, "normalized_t", "normalized_t_panels_v1.csv")

MODELS = [
    "Qwen3.6",
    "Qwen3",
    "GLM-4.7-Flash",
    "Lightning",
    "Nano",
    "Gemma4",
    "OLMoE",
    "GPT-OSS-20B",
    "GPT-OSS-120B",
]

HEADER_TMPL = """% Generated by docs/results/verification_metrics_cpu_20260917/make_paper_tables.py; do not hand-edit.
% Source: {source}
% Intended at 5.5in text width without scaling; 9pt table type.
% Dependencies: booktabs, array, amsmath. No float/caption/label.
"""


def f4(x):
    return "{:.4f}".format(float(x))


def cell(value, lo, hi):
    return (
        "\\begin{tabular}[c]{@{}c@{}}\\(%s\\)\\\\\\([%s,\\,%s]\\)\\end{tabular}"
        % (f4(value), f4(lo), f4(hi))
    )


def plain(value):
    return "\\(%s\\)" % f4(value)


def emit(path, source, colspec, header_cells, rows, tabcolsep="2.5pt"):
    lines = [HEADER_TMPL.format(source=source).rstrip("\n")]
    lines.append("\\begingroup")
    lines.append("\\fontsize{9}{10.5}\\selectfont")
    lines.append("\\setlength{\\tabcolsep}{%s}" % tabcolsep)
    lines.append("\\renewcommand{\\arraystretch}{1.15}")
    lines.append(
        "\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}%s@{}}" % colspec
    )
    lines.append("\\toprule")
    lines.append(" & ".join(header_cells) + " \\\\")
    lines.append("\\midrule")
    for row in rows:
        lines.append(" & ".join(row) + "\\\\[2pt]")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular*}")
    lines.append("\\endgroup")
    text = "\n".join(lines) + "\n"
    with open(path, "w") as fh:
        fh.write(text)
    return text


def stack(*parts):
    return "\\begin{tabular}[c]{@{}c@{}}" + "\\\\".join(parts) + "\\end{tabular}"


def one(df, **keys):
    sel = df
    for k, v in keys.items():
        sel = sel[sel[k] == v]
    assert len(sel) == 1, (keys, len(sel))
    return sel.iloc[0]


# ---------------------------------------------------------------- load inputs
base = pd.read_csv(BASELINE_CSV, float_precision="round_trip")
flips = pd.read_csv(FLIPS_CSV, float_precision="round_trip")
norm = pd.read_csv(NORM_CSV, float_precision="round_trip")

base_m = base[base["metric"] == "mean"]
flips_m = flips[
    (flips["metric"] == "mean")
    & (flips["window"] == "full_step")
    & (flips["sample_set"] == "common_pairs")
    & (flips["receiver_group"] == "all")
]
norm_m = norm[(norm["metric"] == "mean") & (norm["control"] == "paired")]

expected = {}  # (table, model, column) -> formatted string

# ------------------------------------------------------- 1. baseline metrics
rows = []
for m in MODELS:
    r = one(base_m, model=m)
    cells = [m]
    for col in [
        "accuracy",
        "error_recall",
        "clean_false_positive_rate",
        "auroc",
        "mean_gap",
    ]:
        cells.append(cell(r[col], r[col + "_ci_low"], r[col + "_ci_high"]))
        expected[("baseline", m, col)] = (
            f4(r[col]),
            f4(r[col + "_ci_low"]),
            f4(r[col + "_ci_high"]),
        )
    rows.append(cells)

t1_path = os.path.join(TEX_DIR, "verification_baseline_20260917.tex")
t1 = emit(
    t1_path,
    "docs/results/verification_metrics_cpu_20260917/baseline/baseline_panels_v1.csv",
    "lccccc",
    [
        "Model",
        "Accuracy",
        "Error recall",
        stack("Correct-receiver", "FPR"),
        "AUROC",
        "Mean gap \\(g\\)",
    ],
    rows,
)

# --------------------------------------------------------- 2. decision flips
FLIP_SPECS = [
    ("all_router", "paired", "flip_rate_all"),
    ("all_router", "matched", "flip_rate_all"),
    ("all_router", "norm_random", "flip_rate_all"),
    ("post_moe_residual", "paired", "flip_rate_all"),
    ("post_moe_residual", "paired", "delta_accuracy"),
]

rows = []
for m in MODELS:
    cells = [m]
    for arm, ctrl, col in FLIP_SPECS:
        r = one(flips_m, model=m, arm=arm, control=ctrl)
        cells.append(cell(r[col], r[col + "_ci_low"], r[col + "_ci_high"]))
        expected[("flips", m, (arm, ctrl, col))] = (
            f4(r[col]),
            f4(r[col + "_ci_low"]),
            f4(r[col + "_ci_high"]),
        )
    rows.append(cells)

t2_path = os.path.join(TEX_DIR, "decision_flips_20260917.tex")
t2 = emit(
    t2_path,
    "docs/results/verification_metrics_cpu_20260917/flips/flip_panels_v1.csv",
    "lccccc",
    [
        "Model",
        stack("All-router", "paired"),
        stack("All-router", "matched"),
        stack("All-router", "norm-random"),
        stack("Residual", "paired"),
        stack("Residual", "\\(\\Delta\\)accuracy"),
    ],
    rows,
    tabcolsep="1.2pt",  # widest table: 2.5pt overfills \linewidth by 11pt
)

# ----------------------------------------------------- 3. normalized effects
NORM_SPECS = [
    ("full_step", "all_router", "R"),
    ("full_step", "post_moe_residual", "R"),
    ("last_token", "post_moe_residual", "R"),
]

rows = []
for m in MODELS:
    g = one(norm_m, model=m, window="full_step", arm="all_router")
    cells = [m, cell(g["mean_g"], g["mean_g_ci_low"], g["mean_g_ci_high"])]
    expected[("norm", m, "mean_g")] = (
        f4(g["mean_g"]),
        f4(g["mean_g_ci_low"]),
        f4(g["mean_g_ci_high"]),
    )
    for win, arm, col in NORM_SPECS:
        r = one(norm_m, model=m, window=win, arm=arm)
        cells.append(cell(r[col], r[col + "_ci_low"], r[col + "_ci_high"]))
        expected[("norm", m, (win, arm, col))] = (
            f4(r[col]),
            f4(r[col + "_ci_low"]),
            f4(r[col + "_ci_high"]),
        )
    cells.append(plain(g["frac_g_nonpositive"]))
    expected[("norm", m, "frac")] = (f4(g["frac_g_nonpositive"]),)
    rows.append(cells)

t3_path = os.path.join(TEX_DIR, "normalized_effects_20260917.tex")
t3 = emit(
    t3_path,
    "docs/results/verification_metrics_cpu_20260917/normalized_t/normalized_t_panels_v1.csv",
    "lccccc",
    [
        "Model",
        "Mean gap \\(g\\)",
        stack("\\(R\\), all-router", "(full step)"),
        stack("\\(R\\), residual", "(full step)"),
        stack("\\(R\\), residual", "(last token)"),
        stack("Pairs with", "\\(g\\le 0\\)"),
    ],
    rows,
)

# ------------------------------------------------------------- verify output
NUM = re.compile(r"-?\d+\.\d{4}")


def body_rows(path):
    with open(path) as fh:
        text = fh.read()
    body = text.split("\\midrule\n")[1].split("\\bottomrule")[0]
    return [ln for ln in body.strip().split("\n") if ln.strip()]


def check(path, model_keys, per_model):
    rows_read = body_rows(path)
    assert len(rows_read) == len(MODELS), (path, len(rows_read))
    for m, line in zip(MODELS, rows_read):
        assert line.split(" & ")[0] == m, (path, m, line[:40])
        got = NUM.findall(line)
        want = []
        for key in model_keys:
            want.extend(expected[(per_model, m, key)])
        assert got == want, (path, m, got, want)


check(
    t1_path,
    ["accuracy", "error_recall", "clean_false_positive_rate", "auroc", "mean_gap"],
    "baseline",
)
check(t2_path, [(a, c, col) for a, c, col in FLIP_SPECS], "flips")
check(
    t3_path,
    ["mean_g"] + [(w, a, c) for w, a, c in NORM_SPECS] + ["frac"],
    "norm",
)

# ------------------------------------------------------------- provenance
def digest(path):
    with open(path, "rb") as fh:
        raw = fh.read()
    return {"path": path, "bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest()}


prov = {
    "generator": os.path.abspath(__file__),
    "generated_utc": datetime.datetime.now(datetime.timezone.utc)
    .replace(microsecond=0)
    .isoformat()
    .replace("+00:00", "Z"),
    "python": sys.version.split()[0],
    "pandas": pd.__version__,
    "inputs": [digest(BASELINE_CSV), digest(FLIPS_CSV), digest(NORM_CSV)],
    "outputs": [digest(t1_path), digest(t2_path), digest(t3_path)],
    "selection": {
        "baseline": "metric=mean",
        "flips": "metric=mean, window=full_step, sample_set=common_pairs, receiver_group=all",
        "normalized_t": "metric=mean, control=paired",
    },
}
with open(os.path.join(OUT, "paper_tables_provenance_20260917.json"), "w") as fh:
    json.dump(prov, fh, indent=2)
    fh.write("\n")

print("OK: wrote 3 tables and provenance; all cells verified against CSVs.")
for d in prov["outputs"]:
    print(" ", d["path"], d["bytes"], d["sha256"][:16])
