def row(model, **criteria):
    rows = [r for r in EST if r["model"] == model and all(r[k] == v for k, v in criteria.items())]
    assert len(rows) == 1, (model, criteria, len(rows))
    r = rows[0]
    assert r["ci_low"] <= r["mean"] <= r["ci_high"]
    assert r["draws"] == 50000 and r["seed"] == 20260908
    return r


def keep(asset, panel, r):
    INVENTORY.append(
        dict(asset=asset, panel=panel, **{k: v for k, v in r.items() if k != "eligible_pair_ids"})
    )


def figure_text(fig, x, y, text, **kwargs):
    return fig.text(x, y, text, ha=kwargs.pop("ha", "left"), va=kwargs.pop("va", "top"), **kwargs)


def save(fig, name, minfont=8.0, owners=(), check_overlap=True):
    fig.canvas.draw()
    renderer = fig.canvas.get_renderer()
    # Matplotlib keeps Text objects for ticks beyond the view limits although it
    # does not draw them. Exclude only those provably undrawn tick labels.
    undrawn = set()
    for axis in fig.axes:
        for ticks, limits in (
            (axis.xaxis.get_major_ticks(), axis.get_xlim()),
            (axis.yaxis.get_major_ticks(), axis.get_ylim()),
        ):
            lo, hi = sorted(limits)
            for tick in ticks:
                if not lo - 1e-10 <= tick.get_loc() <= hi + 1e-10:
                    undrawn.update((tick.label1, tick.label2))
    texts = [
        t
        for t in fig.findobj(matplotlib.text.Text)
        if t.get_visible() and t.get_text() and t not in undrawn
    ]
    outside = []
    too_small = []
    collisions = []
    for t in texts:
        bb = t.get_window_extent(renderer)
        if bb.x0 < -0.5 or bb.y0 < -0.5 or bb.x1 > fig.bbox.x1 + 0.5 or bb.y1 > fig.bbox.y1 + 0.5:
            outside.append(t.get_text())
        if t.get_fontsize() < minfont - 1e-8:
            too_small.append((t.get_text(), t.get_fontsize()))
    if check_overlap:
        for a, b in itertools.combinations(texts, 2):
            aa = a.get_window_extent(renderer)
            bb = b.get_window_extent(renderer)
            dx = min(aa.x1, bb.x1) - max(aa.x0, bb.x0)
            dy = min(aa.y1, bb.y1) - max(aa.y0, bb.y0)
            if dx > 0.8 and dy > 0.8:
                collisions.append((a.get_text(), b.get_text()))
    owned = []
    for t, rect in owners:
        bb = t.get_window_extent(renderer).transformed(fig.transFigure.inverted())
        x, y, w, h = rect
        assert (
            bb.x0 >= x + 0.003
            and bb.x1 <= x + w - 0.003
            and bb.y0 >= y + 0.003
            and bb.y1 <= y + h - 0.003
        ), (t.get_text(), bb, rect)
        owned.append(t.get_text())
    assert not outside, (name, "outside", outside)
    assert not too_small, (name, "small", too_small)
    if collisions:
        fig.savefig(QA / f"{name}_debug.png", dpi=180)
    assert not collisions, (name, "text overlap", collisions)
    GEOMETRY[name] = dict(
        size_inches=list(fig.get_size_inches()),
        intended_textwidth_inches=WIDTH,
        latex_scale=1.0,
        min_font_pt=min(t.get_fontsize() for t in texts),
        visible_text_count=len(texts),
        text_containment_pass=True,
        independent_text_overlap_pass=True,
        box_owned_text_count=len(owned),
        clipping="none; no tight bounding-box resize",
        axis_contract="see panel specifications and numeric inventory",
    )
    fig.savefig(
        OUT / f"{name}.pdf",
        metadata={
            "CreationDate": None,
            "ModDate": None,
            "Creator": "RouteVerify versioned paper asset generator",
        },
    )
    fig.savefig(OUT / f"{name}.png", dpi=220)
    plt.close(fig)


