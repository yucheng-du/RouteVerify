def semantic_checks():
    result = {}
    for arm in ("router_logits", "moe_output"):
        result[f"residual_gt_{arm}_all_four_windows"] = sum(
            row(m, estimand="residual_minus_arm", arm=arm, control="paired", window=w)["ci_low"] > 0
            for m in MODELS
            for w in WINDOWS
        )
        assert result[f"residual_gt_{arm}_all_four_windows"] == 36
    result["equal_length_gap_decrease_models"] = [
        m
        for m in MODELS
        if row(
            m,
            estimand="gap_window_difference",
            arm="all_router",
            control="paired",
            left="divergence_k",
            right="suffix_k",
        )["ci_high"]
        < 0
    ]
    assert len(result["equal_length_gap_decrease_models"]) == 9
    cats = {"positive": [], "overlaps_zero": [], "negative": []}
    for m in MODELS:
        r = row(
            m, estimand="residual_minus_arm", window="full_step", arm="all_router", control="paired"
        )
        cats[
            "positive" if r["ci_low"] > 0 else "negative" if r["ci_high"] < 0 else "overlaps_zero"
        ].append(m)
    assert (len(cats["positive"]), len(cats["overlaps_zero"]), len(cats["negative"])) == (6, 2, 1)
    assert cats["negative"] == ["GPT-OSS-120B"]
    assert cats["overlaps_zero"] == ["Lightning", "Nano"]
    result["full_step_direct_gap"] = cats
    result["all_router_full_minus_last_positive_models"] = [
        m
        for m in MODELS
        if row(
            m,
            estimand="window_difference",
            left="full_step",
            right="last_token",
            control="paired",
            arm="all_router",
        )["ci_low"]
        > 0
    ]
    assert len(result["all_router_full_minus_last_positive_models"]) == 9
    return result




