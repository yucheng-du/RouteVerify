def nice_upper(x):
    base = 10 ** math.floor(math.log10(x))
    for mult in (1, 1.5, 2, 2.5, 3, 4, 5, 6, 8, 10):
        if mult * base > x:
            return mult * base
    return 10 * base


def fmt(x):
    return f"{x:.3f}".replace("-", "−")


